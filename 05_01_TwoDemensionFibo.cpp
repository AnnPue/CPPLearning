 #include <iostream>
using namespace std;
int dp[1001][1001];// 定义一个表格，初始全是0，大小够存1000行1000列
const int MOD = 1e9+7;          // MOD = 1e9 + 7 是个固定值（1000000007）,防止数字太大，超过范围，结果要对这个数取模

int main() {
    int n,m;
    cin>>n>>m;                  // 输入要计算的行和列，比如输入2 2

    // 边界条件：a[1][1] = 1
    dp[1][1] = 1;

    // 处理i=1且j>=2的情况，a[i][1] = a[i-1][1]
    for(int i=2;i<=n;++i){
        dp[i][1] = dp[i-1][1] %MOD;         // 由于结果可能很大，需要对(10^9 + 7) 取模
    }

    // 处理i>=2且j=1的情况，a[1][j] = a[1][j-1]
    for(int j =2;j<=m;++j){
        dp[1][j] = dp[1][j-1] %MOD;
    }

    // 处理i>=2且j>=2的情况，a[i][j] = a[i-1][1] + a[1][j-1]
    for(int i =2;i<=n;++i){
        for(int j=2;j<=m;++j)
        {
            dp[i][j] = (dp[i-1][j] + dp[i][j-1])%MOD;
        }
    }

    // 输出结果（取模）
    cout<< dp[n][m] % MOD<<endl;
}

