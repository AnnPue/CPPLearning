// 题目要算的是一个二维表格 a[i][j]（i 是行号，j 是列号），规则如下：
// 表格的 “左上角”（第 1 行第 1 列）固定是 1（a[1][1] = 1）；
// 第 1 列的所有格子（不管第几行），值都和它上面的格子一样（比如 a[2][1] = a[1][1]，a[3][1] = a[2][1]，以此类推）；
// 第 1 行的所有格子（不管第几列），值都和它左边的格子一样（比如 a[1][2] = a[1][1]，a[1][3] = a[1][2]，以此类推）；
// 其他格子（不在第 1 行也不在第 1 列），值等于它 “上面格子” 的值加上 “左边格子” 的值（a[i][j] = a[i-1][j] + a[i][j-1]）。
